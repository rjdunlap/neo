export function sampleStroke(stroke: Stroke, spacing = 0.025): Point[] {
  const points: Point[] = [stroke[0]];
  for (let i = 1; i < stroke.length; i++) {
    const a = stroke[i - 1], b = stroke[i];
    const steps = Math.ceil(Math.hypot(b[0] - a[0], b[1] - a[1]) / spacing);
    for (let j = 1; j <= steps; j++) points.push(j === steps ? b : [a[0] + (b[0] - a[0]) * j / steps, a[1] + (b[1] - a[1]) * j / steps]);
  }
  return points;
}

function segmentDistance(p: Point, a: Point, b: Point): number {
  const dx = b[0] - a[0], dy = b[1] - a[1];
  const t = Math.max(0, Math.min(1, ((p[0] - a[0]) * dx + (p[1] - a[1]) * dy) / (dx * dx + dy * dy || 1)));
  return Math.hypot(p[0] - a[0] - dx * t, p[1] - a[1] - dy * t);
}

/** Consume only consecutive checkpoints covered by this finger segment. Never skip a curve. */
export function advanceTrace(points: readonly Point[], index: number, from: Point, to: Point, tolerance: number): number {
  let next = index;
  // A finger returning from far outside the trail must meet the current checkpoint first.
  if (segmentDistance(points[index], from, to) > tolerance) return index;
  while (next + 1 < points.length && segmentDistance(points[next + 1], from, to) <= tolerance) next++;
  return next;
}

export function nameLetters(name: string): string {
  return name.normalize('NFD').replace(/[\u0300-\u036f]/g, '').toUpperCase().replace(/[^A-Z]/g, '').slice(0, 40) || 'PIP';
}
